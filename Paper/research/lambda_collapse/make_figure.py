"""Write Paper/figures/scaling.tex (pgfplots) from stored runs.

(a) exit_p*_s*.json in this directory: outcome exit time from B_eps against lambda^{-n}; median and range over seeds.
(b) Paper/research/gate_network/runs.json: solve time of gradient flow on the full two-block gate network (K = 2) against eps^{-4}.
"""
import glob
import json
import os
import statistics

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", "..", ".."))

runs = {}
for f in glob.glob(os.path.join(here, "exit_p*_s*.json")):
    for r in json.load(open(f)):
        if "T" in r and r["relu_flips"] and max(r["relu_flips"].values()) == 0:
            runs.setdefault(r["lam"], {}).setdefault(r["n"], []).append(r["T"])
colors = {0.5: "outc", 0.6: "midc", 0.7: "theoc"}
marks = {0.5: "*", 0.6: "square*", 0.7: "triangle*"}
a_plots, all_x = [], []
for lam in sorted(runs):
    pts = sorted(runs[lam].items())
    med = [(lam ** -n, statistics.median(v), min(v), max(v), len(v)) for n, v in pts]
    all_x += [m[0] for m in med]
    coords = " ".join(f"({x:.6g},{m:.6g}) +- (0,0)" for x, m, lo, hi, k in med)
    band = " ".join(f"({x:.6g},{lo:.6g})" for x, m, lo, hi, k in med) + " " + \
        " ".join(f"({x:.6g},{hi:.6g})" for x, m, lo, hi, k in reversed(med))
    a_plots.append(f"  \\addplot[draw=none, fill={colors[lam]}, fill opacity=0.18, forget plot] coordinates {{{band}}};\n"
                   f"  \\addplot[{colors[lam]}, mark={marks[lam]}, mark size=1.7pt] coordinates "
                   f"{{{' '.join(f'({x:.6g},{m:.6g})' for x, m, lo, hi, k in med)}}};\n"
                   f"  \\addlegendentry{{$\\mixrate={lam}$}}\n")
# slope-one guide through the median of the first lambda = 0.5 point
g0 = sorted(runs[0.5].items())[0]
gx0, gy0 = 0.5 ** -g0[0], statistics.median(g0[1])
xmin, xmax = min(all_x) / 1.5, max(all_x) * 1.5
guide = f"  \\addplot[black!45, dashed, line width=0.8pt, forget plot] coordinates {{({xmin:.6g},{gy0 * xmin / gx0:.6g}) ({xmax:.6g},{gy0 * xmax / gx0:.6g})}};\n"

ode = json.load(open(os.path.join(root, "Paper", "research", "gate_network", "runs.json")))  # full two-block gate network
series = {}
for r in ode:
    if r["K"] == 2 and r.get("solved_at"):  # every run solves
        series.setdefault((r["p"], r["seed"]), []).append((r["eps"] ** -4, r["solved_at"]))
b_plots, ys, xs = [], [], []
style = {"aligned": "stepc, mark=*", "misaligned": "outc, mark=square*"}
for (p, seed), pts in sorted(series.items(), key=lambda kv: (str(kv[0][1]), kv[0][0])):
    pts.sort()
    xs += [x for x, _ in pts]
    ys += [y for _, y in pts]
    st = style["aligned" if str(seed).startswith("aligned") else "misaligned"]
    b_plots.append(f"  \\addplot[{st}, mark size=1.5pt, line width=0.7pt, opacity=0.85] coordinates "
                   f"{{{' '.join(f'({x:.6g},{y:.6g})' for x, y in pts)}}};\n")
bx0, bx1 = min(xs) / 1.3, max(xs) * 1.3
by0 = min(ys)
b_guide = f"  \\addplot[black!45, dashed, line width=0.8pt] coordinates {{({min(xs):.6g},{by0:.6g}) ({max(xs):.6g},{by0 * max(xs) / min(xs):.6g})}};\n"

tex = r"""%% Generated by Paper/research/lambda_collapse/make_figure.py -- do not edit by hand.
\definecolor{stepc}{HTML}{0072B2}\definecolor{outc}{HTML}{D55E00}\definecolor{theoc}{HTML}{009E73}\definecolor{midc}{HTML}{CC79A7}
\begin{tikzpicture}
\pgfplotsset{every axis/.style={width=0.48\linewidth, height=5cm, axis line style={black!80}, tick style={black!80},
  tick label style={font=\footnotesize}, label style={font=\small}, title style={font=\small, at={(0,1)}, anchor=south west, xshift=-2pt},
  axis x line*=bottom, axis y line*=left, ymajorgrids, major grid style={black!12}}, every axis plot/.append style={line width=1pt}}
\begin{loglogaxis}[name=pa, title={\textbf{(a)} Outcome plateau: exit time from $\initball$}, xlabel={$\mixrate^{-n}$}, ylabel={Exit time},
  legend style={font=\scriptsize, draw=none, fill=none, at={(0.98,0.03)}, anchor=south east}, legend cell align=left]
""" + "".join(a_plots) + guide + r"""\end{loglogaxis}
\begin{loglogaxis}[name=pb, at={(pa.east)}, anchor=west, xshift=1.6cm, title={\textbf{(b)} Step learning: solve time, full network},
  xlabel={$\initscale^{-4}$}, ylabel={Solve time}]
""" + "".join(b_plots) + b_guide + r"""  \node[anchor=north west, font=\scriptsize, text=stepc] at (rel axis cs:0.03,0.97) {aligned};
  \node[anchor=north west, font=\scriptsize, text=outc] at (rel axis cs:0.03,0.88) {misaligned};
  \node[anchor=south east, font=\scriptsize, text=black!60] at (rel axis cs:0.97,0.03) {dashed: slope $1$};
\end{loglogaxis}
\end{tikzpicture}
"""
open(os.path.join(root, "Paper", "figures", "scaling.tex"), "w").write(tex)
for lam in sorted(runs):
    print(lam, {n: len(v) for n, v in sorted(runs[lam].items())})
print("ode series", len(series))
