"""Generate the single notation table from notation.tex's @notation rows."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
rows = []
for line in (root / 'notation.tex').read_text().splitlines():
    if line.startswith('% @notation:'):
        symbol, meaning = line.split(':', 1)[1].strip().split(' || ', 1)
        rows.append(f'{symbol} & {meaning}\\\\')
content = r'''% Generated by tools/generate_notation_table.py. Edit notation.tex.
\begin{center}\small
\fitwidth{\begin{tabular}{@{}ll@{}}
\toprule
Symbol & Meaning\\
\midrule
''' + '\n'.join(rows) + r'''
\bottomrule
\end{tabular}}
\captionof{table}{\textbf{Notation.} Symbols used in one proof only are defined there.
Named subscripts are roman; indices are italic.}
\label{tab:notation}
\end{center}
'''
(root / 'notation-table.tex').write_text(content)
