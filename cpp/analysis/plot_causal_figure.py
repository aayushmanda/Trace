#!/usr/bin/env python3
"""Regenerate figures/causal_intervention.tex (pgfplots, inline coordinates) from the 20-seed sweep.

(a) wrong-lag correlation E_dist vs updates at p=1/4 (seed mean)
(b) cumulative fraction of seeds solved (>=99.9% exact rollout) vs updates at p=1/4
(c) final solve rate vs p, Natural vs Suppressed, with Wilson 95% intervals
(d) Block-2 prefix attention share on lag n (true) and lag 1 at 400 updates vs p, Natural vs Suppressed

By default, refuses to overwrite figures/causal_intervention.tex until all four p values
(0.05, 0.25, 0.5, 0.75) have completed runs (pass --force to override).
"""
import glob
import os
import re
import sys
from collections import defaultdict
from aggregate import load, wilson, SOLVE, FINAL

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SWEEP_DIR = os.environ.get("SWEEP_DIR", os.path.join(ROOT, "results", "causal_intervention", "sweep"))
OUT = os.environ.get(
    "FIG_OUT",
    os.path.join(ROOT, "papers", "silent_routing", "figures", "causal_intervention.tex"),
)
FORCE = "--force" in sys.argv[1:]

runs = defaultdict(list)
for sub in ("main", "rel600", "rel1000"):
    for path in glob.glob(os.path.join(SWEEP_DIR, sub, "*.csv")):
        m = re.search(r"n(\d+)_p([\d.]+)_m(\d+)_s(\d+)\.csv", path)
        p, mode = float(m[2]), int(m[3])
        rows = load(path)
        if not rows or int(rows[-1]["step"]) < FINAL:
            continue
        key = (p, mode if mode != 3 else f"3-{sub}")
        runs[key].append(rows)

REQUIRED_PS = (0.05, 0.25, 0.5, 0.75)
missing = [
    f"(p={p}, mode={k}): {len(runs.get((p, k), []))}/20"
    for p in REQUIRED_PS
    for k in (0, 1)
    if len(runs.get((p, k), [])) < 20
]
for k in (0, 1, 2, 4, "3-rel600"):
    if len(runs.get((0.25, k), [])) < 20:
        missing.append(f"(p=0.25, mode={k}): {len(runs.get((0.25, k), []))}/20")

if missing and not FORCE:
    sys.stderr.write(
        "Sweep incomplete; keeping existing figures/causal_intervention.tex (pass --force to overwrite):\n  "
        + "\n  ".join(dict.fromkeys(missing))
        + "\n"
    )
    sys.exit(1)

STEPS = sorted({int(r["step"]) for rs in runs.values() for rows in rs for r in rows})


def mean_curve(key, col):
    pts = []
    for s in STEPS:
        v = [r[col] for rows in runs[key] for r in rows if int(r["step"]) == s]
        if v:
            pts.append((s / 1000, sum(v) / len(v)))
    return pts


def solved_curve(key):
    pts = []
    n_seeds = len(runs[key])
    for s in STEPS:
        k = sum(any(r["rollout_acc"] >= SOLVE and int(r["step"]) <= s for r in rows) for rows in runs[key])
        pts.append((s / 1000, k / n_seeds))
    return pts


def coords(pts):
    return " ".join(f"({x:.3f},{y:.4f})" for x, y in pts)


STYLE = {
    0: ("stepc", "solid", "Natural"),
    1: ("outc", "solid", "Suppressed ($\\Pi_0^{(p)}$)"),
    "3-rel600": ("modelc", "densely dashdotted", "Restored at $0.6$k"),
    4: ("theoc", "densely dashed", "Calibrated $V(0){=}c^\\star$"),
    2: ("ctrlc", "densely dotted", "External offset"),
}
P = 0.25

L = []
w = L.append
w("%% Generated by cpp/analysis/plot_causal_figure.py from the 20-seed sweep. Do not edit by hand.")
w("\\definecolor{stepc}{HTML}{0072B2}\\definecolor{outc}{HTML}{D55E00}\\definecolor{theoc}{HTML}{009E73}")
w("\\definecolor{modelc}{HTML}{7B4F9E}\\definecolor{mutedc}{HTML}{6E6E6E}\\definecolor{ctrlc}{HTML}{2B2B2B}")
w("\\begin{tikzpicture}")
w("\\pgfplotsset{every axis/.style={scale only axis, width=0.175\\textwidth, height=2.5cm,"
  " axis line style={black!80, line width=0.55pt}, tick style={black!75, line width=0.45pt},"
  " tick label style={font=\\scriptsize}, label style={font=\\footnotesize}, ylabel style={yshift=-2pt},"
  " title style={font=\\footnotesize, at={(0.5,1.03)}, anchor=south}, axis x line*=bottom, axis y line*=left,"
  " scaled ticks=false, ymajorgrids, major grid style={black!8, line width=0.35pt}, clip=false},"
  " every axis plot/.append style={line width=1.0pt}}")

# (a)
w("\\begin{axis}[name=ca, title={\\textbf{(a)} $\\widehat E_{\\mathrm{dist}}$ ($p{=}\\tfrac14$)}, xlabel={Updates ($\\times10^3$)},"
  " xmin=0, xmax=1.2, ymin=-0.004, ymax=0.142, xtick={0,0.4,0.8,1.2}, ytick={0,0.04,0.08,0.125}, yticklabels={$0$,$0.04$,$0.08$,$0.125$}]")
w("\\addplot[mutedc, densely dashed, line width=0.7pt, domain=0:1.2, samples=2, forget plot] {0.125};")
w("\\draw[modelc!65, densely dotted, line width=0.7pt] (axis cs:0.60,-0.004) -- (axis cs:0.60,0.136);")
w("\\node[anchor=west, font=\\tiny, text=modelc!90!black, inner sep=1pt] at (axis cs:0.62,0.109) {release};")
for key in (1, "3-rel600", 0, 4, 2):
    if (P, key) in runs:
        c, d, _ = STYLE[key]
        w(f"\\addplot[{c}, {d}] coordinates {{{coords([q for q in mean_curve((P, key), 'E_dist') if q[0] <= 1.2])}}};")
w("\\end{axis}")

# (b)
w("\\begin{axis}[name=cb, at={($(ca.east)+(1.05cm,0)$)}, anchor=west, title={\\textbf{(b)} Fraction solved ($p{=}\\tfrac14$)},"
  " xlabel={Updates ($\\times10^3$)}, xmin=0, xmax=2.4, ymin=0, ymax=1.03, xtick={0,0.8,1.6,2.4}, ytick={0,0.5,1},"
  " legend to name=causallegend, legend columns=5, legend style={font=\\scriptsize, draw=black!16, fill=black!1.5,"
  " rounded corners=1.5pt, inner xsep=5pt, inner ysep=2pt, column sep=6pt}]")
for key in (0, 1, "3-rel600", 4, 2):
    if (P, key) in runs:
        c, d, lab = STYLE[key]
        rs = runs[(P, key)]
        k_sol = sum(rows[-1]["rollout_acc"] >= SOLVE for rows in rs)
        w(f"\\addplot[{c}, {d}, const plot] coordinates {{{coords(solved_curve((P, key)))}}};")
        w(f"\\addlegendentry{{{lab} (${k_sol}/{len(rs)}$)}}")
w("\\end{axis}")

# (c)
ps = sorted({p for (p, k) in runs if k in (0, 1) and p != P} | {P})
w("\\begin{axis}[name=cc, at={($(cb.east)+(0.95cm,0)$)}, anchor=west, title={\\textbf{(c)} Solved at $2.4$k vs.\\ $p$},"
  " xlabel={$p$}, xmin=0, xmax=0.8, ymin=0, ymax=1.05, xtick={0.05,0.25,0.5,0.75}, xticklabels={$.05$,$.25$,$.5$,$.75$}, ytick={0,0.5,1}]")
for key, dx in ((0, -0.010), (1, 0.010)):
    c, _, _ = STYLE[key]
    pts = []
    for p in ps:
        if (p, key) not in runs:
            continue
        rs = runs[(p, key)]
        k = sum(rows[-1]["rollout_acc"] >= SOLVE for rows in rs)
        lo, hi = wilson(k, len(rs))
        ph = k / len(rs)
        pts.append(f"({p+dx:.3f},{ph:.3f})")
        w(f"\\draw[{c}, line width=0.6pt] (axis cs:{p+dx:.3f},{lo:.3f}) -- (axis cs:{p+dx:.3f},{hi:.3f});")
    w(f"\\addplot[{c}, only marks, mark={'*' if key == 0 else 'square*'}, mark size=1.5pt] coordinates {{{' '.join(pts)}}};")
w("\\end{axis}")

# (d)
d_vals = [
    sum(r[col] for rows in runs[(p, key)] for r in rows if int(r["step"]) == 400) / len(runs[(p, key)])
    for key in (0, 1)
    for col in ("prefix_lag_n", "prefix_lag_1")
    for p in ps
    if (p, key) in runs and any(int(r["step"]) == 400 for rows in runs[(p, key)] for r in rows)
]
ymax_d = max(0.28, round(max(d_vals, default=0.25) * 1.22, 2))
w(f"\\begin{{axis}}[name=cd, at={{($(cc.east)+(0.95cm,0)$)}}, anchor=west, title={{\\textbf{{(d)}} Prefix share at $0.4$k}},"
  f" xlabel={{$p$}}, xmin=0, xmax=0.8, ymin=0, ymax={ymax_d:.2f}, yticklabel style={{/pgf/number format/fixed, /pgf/number format/precision=2}},"
  f" xtick={{0.05,0.25,0.5,0.75}}, xticklabels={{$.05$,$.25$,$.5$,$.75$}}]")
w("\\addplot[mutedc, densely dashed, line width=0.65pt, domain=0:0.8, samples=2, forget plot] {0.125};")
for key in (0, 1):
    c, _, _ = STYLE[key]
    for col, d, mk in (("prefix_lag_n", "solid", "*"), ("prefix_lag_1", "densely dashed", "o")):
        pts = []
        for p in ps:
            if (p, key) not in runs:
                continue
            v = [r[col] for rows in runs[(p, key)] for r in rows if int(r["step"]) == 400]
            if v:
                pts.append((p, sum(v) / len(v)))
        w(f"\\addplot[{c}, {d}, mark={mk}, mark size=1.3pt] coordinates {{{coords(pts)}}};")
w("\\node[anchor=north east, font=\\tiny, align=right] at (rel axis cs:0.98,0.98) {solid: lag $n$\\\\ dashed: lag $1$};")
w("\\end{axis}")
w("\\node[anchor=north] at ($(cb.south east)!0.5!(cc.south west)+(0,-0.72cm)$) {\\pgfplotslegendfromname{causallegend}};")
w("\\end{tikzpicture}")

open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", OUT, {f"{k}": len(v) for k, v in runs.items()})
